### Decay cards (EvtGen format) ###
# Top mother psi(4260) (BESIII/KkMC convention); ISR is generated by KkMC at the
# top level and FSR by PHOTOS/VLL in the J/psi -> l+ l- decay.

# Mode 1: e+e- -> pi+ pi- X(3823), X(3823) -> gamma chi_c1, chi_c1 -> gamma J/psi, J/psi -> e+ e-
decay_card_chic1_ee = <<~DECAYCARD
    Decay psi(4260)
    1.0000 pi+ pi- X(3823)      PHSP;
    Enddecay

    Decay X(3823)
    1.0000 gamma chi_c1         PHSP;
    Enddecay

    Decay chi_c1
    1.0000 gamma J/psi          PHSP;
    Enddecay

    Decay J/psi
    1.0000 e+ e-                PHOTOS VLL;
    Enddecay

    End
DECAYCARD

# Mode 2: same as mode 1 but J/psi -> mu+ mu-
