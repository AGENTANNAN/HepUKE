### Event selection (BOSS) ###
# All four modes (gamma chi_c1 / gamma chi_c2, J/psi -> e+e- / mu+mu-) share the
# identical final state pi+ pi- gamma gamma l+ l- and the identical selection chain;
# they are separated later in ROOT by the M(gamma_H J/psi) window. A single Algorithm
# instance is therefore used for all of them.
alg_name = "PiPiGammaGammaLL"
my_algorithm = Algorithm.new(alg_name)
my_algorithm.set_header(["#{alg_name}Alg/#{alg_name}.h"])
            .set_constant({"ECMS" => [:double, 4.260]})   # nominal point; per-run beam energy used at execution for the scan
            .set_alias({"std::vector<double>" => "Vdouble"})

event_selection = Selection.new
event_selection.select_track {          # Charged track selection
                  cos_theta   0.93      # |cos(theta)| < 0.93
                  Vz          10.0      # |Vz| < 10 cm along the beam axis
                  Vr          1.0       # Vr < 1 cm in the transverse plane
                  nChrp       "==2"     # Exactly 2 positively charged tracks
                  nChrn       "==2"     # Exactly 2 negatively charged tracks
                  nNet        "==0"     # Net charge zero
                }
               .select_photon {         # Photon selection
                  tdc_emc_start      0       # TDC start time
                  tdc_emc_end        14      # TDC end time
                  angle_to_track     10.0    # At least 10 degrees from the nearest charged track
                  energyThreshold_b  0.025   # 25 MeV threshold in the EMC barrel
                  energyThreshold_e  0.050   # 50 MeV threshold in the EMC endcap
                  nGam               ">=2"   # At least two photon candidates
                }
               .pid(method: :probability) {   # Particle identification (probability method)
                  prob_cut   0.001            # PID probability > 0.001
                  identify_high_momentum_leptons treat_as_lepton_if_momentum_above: 1.0,
                                                 treat_as_electron_if_energy_above: 0.6  # p>1.0 GeV -> lepton; EMC eraw>0.6 GeV -> electron, else muon
                  identify :pion, against: [:kaon]   # pi+/pi- separation from kaons
                  npip   "==1"                # Exactly one pi+
                  npim   "==1"                # Exactly one pi-
                  nlp    "==1"                # Exactly one l+
                  nlm    "==1"                # Exactly one l-
                }
               .kinematic_fit([:pip, :pim, :gamma, :gamma, :lp, :lm]) {  # 4C fit to e+e- -> pi+pi- gamma gamma l+l-
                  nominal                  # Mark as the nominal fit (corrected four-momenta are kept)
                  constrain_four_momentum  # Constrain total four-momentum to the CMS energy
                  chi2_cut 200             # Loose chi2 < 200 (tight cut optimised later in ROOT)
                }

# Attach a representative decay card (the pi+pi-gamma-gamma-l+l- final state is common
# to all four signal modes, so the generated header covers every one of them).
my_algorithm.with_decay_card(decay_card_chic1_ee).apply(event_selection)

# Execute on real data, matching inclusive MC, and all exclusive signal MC samples
root_files = my_algorithm.execute_on(data_points + incMC_points +
                                     exMC_chic1_ee + exMC_chic1_mumu +
                                     exMC_chic2_ee + exMC_chic2_mumu)