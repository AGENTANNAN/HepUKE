incMCs      = [incMC_4009, incMC_4230, incMC_4260, incMC_4360]

# ----------------------------------------------------------------------------
# Signal decay cards: e+e- -> gamma_ISR X(3872) and e+e- -> gamma_ISR psi(3686),
# both followed by -> pi+ pi- J/psi with J/psi -> l+ l-.
# ISR is generated by the KKMC / vectorISR machinery; the In the card the ISR
# photon is kept as an explicit daughter of the psi(4260) so that the exclusive
# final state gamma pi+ pi- l+ l- is complete.
# ----------------------------------------------------------------------------
# X(3872) signal, J/psi -> e+ e-
decay_card_X3872_ee = <<~DECAYCARD
    Decay psi(4260)
    1.0000 gamma X(3872) PHSP;
    Enddecay

    Decay X(3872)
    1.0000 pi+ pi- J/psi PHSP;
    Enddecay

    Decay J/psi
    1.0000 e+ e- PHOTOS VLL;
    Enddecay

    End
DECAYCARD

# X(3872) signal, J/psi -> mu+ mu-
