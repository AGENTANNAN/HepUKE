# ============================================================================
# arXiv:1505.02559v1 (BESIII)
# An Improved Limit for Gamma_ee of X(3872) and Gamma_ee Measurement of psi(3686)
#
# ISR (untagged) search for e+e- -> gamma_ISR X(3872) -> gamma_ISR pi+ pi- J/psi,
# with J/psi -> l+ l- (l = e, mu). The same final state contains a large
# e+e- -> gamma_ISR psi(3686) -> gamma_ISR pi+ pi- J/psi component, which is used
# to measure Gamma_ee[psi(3686)] as a benchmark.
#
# Data: 2.94 fb^-1 at sqrt(s) = 4.009, 4.230, 4.260 and 4.360 GeV.
# The ISR photon is emitted at small polar angles (|cos(theta_ISR)| > 0.95),
# is not detected, and is reconstructed from the missing momentum of the event
# (untagged ISR method).
#
# BOSS part only: decay cards, exclusive MC, event selection up to the 2C
# kinematic fit.
# ============================================================================

### Dataset description ###
# Real data at the four centre-of-mass energies used in the analysis
data_4009 = DatasetManager.real_data.find("703_4009")   # 482 pb^-1
data_4230 = DatasetManager.real_data.find("703_4230")   # 1092 pb^-1
data_4260 = DatasetManager.real_data.find("703_4260")   # 826 pb^-1
data_4360 = DatasetManager.real_data.find("703_4360")   # 540 pb^-1

