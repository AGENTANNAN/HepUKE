### Event selection (BOSS) ###
# --- J/psi -> e+ e- channel -------------------------------------------------
alg_name_ee = "ISRX3872EE"
alg_ee = Algorithm.new(alg_name_ee)
alg_ee.set_header(["#{alg_name_ee}Alg/#{alg_name_ee}.h"])
      .set_alias({"std::vector<double>" => "Vdouble"})
      # Multi-energy scan: ECMS is injected per dataset at run time, so no
      # ECMS constant is declared here.

# --- J/psi -> mu+ mu- channel -----------------------------------------------
alg_name_mumu = "ISRX3872MuMu"
alg_mumu = Algorithm.new(alg_name_mumu)
alg_mumu.set_header(["#{alg_name_mumu}Alg/#{alg_name_mumu}.h"])
        .set_alias({"std::vector<double>" => "Vdouble"})

# Common selection: four charged tracks with net charge zero, lepton/pion
# separation by momentum (p > 1 GeV/c -> lepton, p < 600 MeV/c -> pion), then
# the 2C kinematic fit for the untagged gamma_ISR pi+ pi- l+ l- final state.
event_selection = Selection.new
event_selection.select_track {
                  cos_theta   0.93   # |cos(theta)| < 0.93 in the MDC
                  Vz          10.0   # |Vz| < 10 cm along the beam direction
                  Vr          1.0    # Vr < 1 cm in the plane perpendicular to the beam
                  nChrp       "==2"  # exactly two positively charged tracks
                  nChrn       "==2"  # exactly two negatively charged tracks
                  nNet        "==0"  # net charge zero
                }
               .pid(method: :probability) {
                  prob_cut 0.001
                  # The J/psi carries most of the total momentum, so leptons are
                  # the high-momentum tracks (p > 1 GeV/c in the lab frame)
                  identify_high_momentum_leptons treat_as_lepton_if_momentum_above: 1.0,
                                                 treat_as_electron_if_energy_above: 0.4
                  identify :pion, against: [:kaon, :proton]  # the two pions
                  nlp  "==1"
                  nlm  "==1"
                  npip "==1"
                  npim "==1"
                }
               # Pion candidates must have lab momentum below 600 MeV/c
               .for_each(:pip) { where { p > 0.6 }; remove }
               .for_each(:pim) { where { p > 0.6 }; remove }
               # 2C kinematic fit of the untagged final state gamma_ISR pi+ pi- l+ l-:
               # the ISR photon is missing (inferred from the missing momentum) and
               # constrained to a zero mass, and the lepton pair is constrained to
               # the nominal J/psi mass
               .kinematic_fit([:pip, :pim, :lp, :lm]) {
                  nominal
                  miss_track_of :gamma                                          # undetected ISR photon, mass constrained to zero
                  invariant_mass_of(:lp, :lm).constrain_to_nominal_mass_of(:jpsi)  # J/psi mass constraint
                  chi2_cut 200   # loose BOSS-pass cut; the paper's chi2_2C < 15 is applied in ROOT
                }

# Dedicated selection objects for the two lepton channels
selection_ee   = event_selection.dup
selection_mumu = event_selection.dup

